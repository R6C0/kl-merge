#!/usr/bin/env python3
"""
kl_arc2_kit.py - STAGE the ARC2 kit (offline Arcade baseline of the AI heisters on the 10 maps ARC1 lacks), without launching anything (2026-11-01, wk-botscore-1101).

    python tools/kl_arc2_kit.py [--out C:/kl_build_1024/week_1028/arc2] [--base-ini <ARC1 KLHook ini>] [--hook <dir of the TEST dll>] [--repo <worktree>]

Models gen_arc1.py (C:\\kl_build_1024\\week_1028\\arc1): the same TEST dll (ArcadeProbe=1, log only) and ini, one seat that stands still, the 7 AI heisters
play with the game's own brain, kl_arcade_baseline.py reads the 'arcadeprobe:' lines. Writes into --out:
    KLHook_ARC2.ini          the ARC1 base ini (ArcadeProbe=1 already in it), tag renamed
    ARC2_<MAP>.ini           one menu script per map
    maps_ARC2.txt, run_arc2.sh, loadcheck.py (copied from the ARC1 kit, or a built-in copy), README.txt
Maps: DM01B DM02 DM03 DM03A DM05A DM06B DM07 DM09 DM11B DD10. Slot / page / entry are the VERIFIED ones of the live_1026 smoke inis
(C:\\kl_build_1024\\live_1026\\<MAP>.ini: 'sel HeistLevel_Px 0xceceec <entry>' after 'waitwin HeistPlayMenuX'); page 2 = 6 x DOWN on HeistModeMenu, page 3 = 7 x DOWN
(kl_playtest.py INSTALLED_DOWN). The ten are expansion maps: they must be installed in the game folder (KLExpansion), as for ARC1's DM01 / DM06.
DM09 (Retomoto) gets a longer cap (secs 1000, AutoExit / MaxRunMs 900): it loads slowly and Q31 gave it a 1100 s bench.
Reads/writes only --out. Never starts the game; the run script does, and only when someone runs it.
"""
import argparse, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TAG = 'ARC2'
OUT = 'C:/kl_build_1024/week_1028/arc2'
ARC1 = 'C:/kl_build_1024/week_1028/arc1'
HOOK = 'C:/kl-merge/wt/wk-arcbase-1101/klhook/out_arcbase_test'
REPO = 'C:/kl-merge/wt/wk-arcbase-1101'
# map | slot | page | entry   (from the live_1026 smoke inis, see the module docstring)
MAPS = [('DM01B', 'F03', 3, 2), ('DM02', 'F02', 2, 1), ('DM03', 'F03', 2, 2), ('DM03A', 'F07', 2, 5), ('DM05A', 'F01', 3, 0),
        ('DM06B', 'F02', 3, 1), ('DM07', 'F06', 3, 4), ('DM09', 'F06', 2, 4), ('DM11B', 'F04', 3, 3), ('DD10', 'F07', 3, 5)]
DOWN = {2: 6, 3: 7}
SECS = {'DM09': 1000}
LONG_MS = {'DM09': 900000}

HEAD = """; {tag} {m}: OFFLINE Arcade, 1 seat, {slot} page {page} entry {entry}; ArcadeProbe log only. Generated by tools/kl_arc2_kit.py (wk-botscore 11-01).
; The seat stands still (cops hurt it 0.001 x so the round is not ended by its death); the AI heisters play with the game's own brain.
[Balance]
CopToYou=0.001
PointBlankToYou=0.0
[Auto]
Enable=1
Hooks=0
Nodes=0
EndHooks=1
CmdDrop=DefaultScene,AutoExit
CmdAdd=-o DisableSplashScreens -o AutoExit={autoexit}
StallMs=300000
MaxRunMs={maxrun}
LoadedMs=0
Unfocused=1
BlockReal=1
FirstChance=1
PosLogMs=5000
[Script]
1=waitwin CampaignMenu 180000
2=settle 15 150 60000
3=tapuntil ESCAPE MainMenu 10000 3
4=settle 8 150 30000
5=wait 1500
6=tap DOWN
7=wait 1200
8=tapuntil RETURN HeistModeMenu 15000 2
9=settle 8 150 30000
10=wait 3000
11=windows
"""

LOADCHECK = '''"""loadcheck.py LOG MAP - exit 0 only if the 'expansion: LOAD ... rule MAP' lines AFTER the script's 'starting entry' marker name MAP.
The startup scan logs 'LOAD F05/F08/F09 ... rule DDxx' before any menu, so a bare 'rule MAP' grep proves nothing."""
import re, sys
log, want = sys.argv[1], sys.argv[2]
try:
    lines = open(log, 'rb').read().decode('latin1').splitlines()
except OSError as e:
    print('  LOAD CHECK: cannot read %s (%s)' % (log, e)); sys.exit(2)
at = next((i for i, l in enumerate(lines) if 'starting entry' in l), None)
if at is None:
    print("  LOAD CHECK: no 'starting entry' marker - the menu script never reached the start (%s)" % want); sys.exit(2)
rules = [m.group(1) for l in lines[at:] for m in [re.search(r'expansion: LOAD F\\w+: .*? rule (D[DM]\\d\\d)', l)] if m]
if not rules:
    print("  LOAD CHECK: no LOAD line after 'starting entry' - the map did not load (%s)" % want); sys.exit(2)
if want not in set(rules):
    print('  LOAD CHECK WRONG MAP: wanted %s, the load named %s - discard this run' % (want, ','.join(sorted(set(rules))))); sys.exit(1)
if set(rules) != {want}:
    print('  LOAD CHECK: %s loaded, but also %s named after the start' % (want, ','.join(sorted(set(rules) - {want}))))
print('  load check ok: rule %s after the start marker' % want)
'''


def script_lines(m, slot, page, entry):
    ls = []
    for _ in range(DOWN[page]):
        ls += ['tap DOWN', 'wait 500']
    ls += ['wait 2500', 'windows', 'tap RETURN', 'waitwin HeistPlayMenu%d 8000' % page, 'wait 3000', 'windows',
           'sel HeistLevel_P%d 0xceceec %d' % (page, entry), 'wait 2500', 'expect 0xceceec %d' % entry,
           'log starting entry %d = %s (%s) page %d' % (entry, m, slot, page), 'msg HeistLevel_P%d StartGame' % page,
           'waitload 300000', 'log level loaded: %s' % m, 'wait 23000', 'peek 0x168e598+0x70 session-state-must-be-0x19', 'pos spawn']
    for k in range(1, 6):
        ls += ['wait 30000', 'pos t%d' % (k * 30)]
    ls += ['waitstate 0x1f 300000', 'log %s %s: round over (state 0x1f)' % (TAG, m), 'wait 8000', 'pass 1000']
    return ls


def ini_text(m, slot, page, entry):
    body = HEAD.format(tag=TAG, m=m, slot=slot, page=page, entry=entry, autoexit=LONG_MS.get(m, 700000) // 1000, maxrun=LONG_MS.get(m, 690000))
    return body + ''.join('%d=%s\r\n' % (n, l) for n, l in enumerate(script_lines(m, slot, page, entry), 12))


def run_script(out, hook, repo):
    maps = ','.join(m for m, _, _, _ in MAPS)
    return f"""#!/bin/sh
# {TAG}: offline Arcade baseline (1 seat) on the 10 maps ARC1 lacks, TEST dll {hook}. Touch {out}/PAUSE to stop before the next map.
# Needs the game closed and the owner away (kl_solo_test refuses a running kl2.exe / recent owner input; --owner-away skips the idle gate).
# STAGED, NOT RUN (wk-botscore-1101). Needs the TEST dll built from klhook with ArcadeProbe (klhook/klbotfill.c klbf_ap_run) and the ten expansion maps installed.
cd {repo} || exit 1
Q={out}
while IFS='|' read -r tag map slot page secs; do
  [ -z "$tag" ] && continue
  if [ -f $Q/PAUSE ]; then echo "$(date +%H:%M:%S) PAUSE file: stopping before $map"; break; fi
  echo "$(date +%H:%M:%S) {TAG}_$map start (slot $slot page $page secs $secs)"
  python tools/kl_solo_test.py --hook {hook} --n 1 --secs $secs --tag {TAG}_$map --owner-away --base $Q/KLHook_{TAG}.ini \\
    --ini1 $Q/{TAG}_${{map}}.ini > $Q/{TAG}_${{map}}_run.txt 2>&1
  echo "$(date +%H:%M:%S) {TAG}_$map exit $?"
  L="G:/SteamLibrary/steamapps/common/Kane and Lynch Dead Men/KL_PortTools/build/klhook/solo/{TAG}_$map/inst1/KLHook.log"
  python $Q/loadcheck.py "$L" $map
done < $Q/maps_{TAG}.txt
python {repo}/tools/kl_arcade_baseline.py --tag {TAG} --maps {maps}
python {repo}/tools/kl_online_vs_arcade.py --prefix Q31 --maps {maps} --arcade {repo}/re/arcade_baseline_1101_arc2.md
"""


def make_base(arc1_ini, out):
    """ARC1's base ini with the tag renamed; it must already carry ArcadeProbe=1 (log only)."""
    s = open(arc1_ini, 'rb').read().decode('utf-8')
    if not re.search(r'^ArcadeProbe=1', s, re.M):
        raise SystemExit('%s has no ArcadeProbe=1: not an ARC1 base ini' % arc1_ini)
    s = s.replace('; ARC1 (', '; ARC2 (', 1)
    open(os.path.join(out, 'KLHook_%s.ini' % TAG), 'wb').write(s.encode('utf-8'))


def stage(out, base_ini, hook, repo, arc1_dir=ARC1):
    os.makedirs(out, exist_ok=True)
    make_base(base_ini, out)
    for m, slot, page, entry in MAPS:
        open(os.path.join(out, '%s_%s.ini' % (TAG, m)), 'wb').write(ini_text(m, slot, page, entry).encode('utf-8'))
    open(os.path.join(out, 'maps_%s.txt' % TAG), 'w', encoding='utf-8', newline='\n').write(
        ''.join('%s|%s|%s|%d|%d\n' % (m, m, slot, page, SECS.get(m, 760)) for m, slot, page, _ in MAPS))
    open(os.path.join(out, 'run_%s.sh' % TAG.lower()), 'w', encoding='utf-8', newline='\n').write(run_script(out, hook, repo))
    lc = os.path.join(arc1_dir, 'loadcheck.py')
    if os.path.isfile(lc):
        shutil.copyfile(lc, os.path.join(out, 'loadcheck.py'))
    else:
        open(os.path.join(out, 'loadcheck.py'), 'w', encoding='utf-8', newline='\n').write(LOADCHECK)
    open(os.path.join(out, 'README.txt'), 'w', encoding='utf-8', newline='\n').write(
        'ARC2 kit (staged 2026-11-01 by tools/kl_arc2_kit.py, NOT RUN): the offline Arcade baseline on DM01B DM02 DM03 DM03A DM05A DM06B DM07 DM09 DM11B DD10.\n'
        'Run when the game is free and the owner is away:  sh %s/run_arc2.sh   (touch %s/PAUSE to stop before the next map)\n'
        'About 10 x 7 min (DM09 up to 17 min). Result: the baseline table at the end; paste it into re/arcade_baseline_1101_arc2.md (same columns as ARC1).\n'
        'Before the run: the TEST dll at %s must carry ArcadeProbe (klhook/klbotfill.c), and the ten expansion maps must be installed (as ARC1 needed DM01 / DM06).\n'
        'Check each map with loadcheck.py (the run script does): a wrong map loaded = discard that run.\n' % (out, out, hook))
    return [m for m, _, _, _ in MAPS]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=OUT)
    ap.add_argument('--base-ini', default=ARC1 + '/KLHook_ARC1.ini')
    ap.add_argument('--hook', default=HOOK)
    ap.add_argument('--repo', default=REPO)
    a = ap.parse_args(argv)
    maps = stage(a.out, a.base_ini, a.hook, a.repo)
    print('staged %s kit for %d maps in %s: %s' % (TAG, len(maps), a.out, ' '.join(maps)))
    print('RESULT: OK (staged, not run)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
