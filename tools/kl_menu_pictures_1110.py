"""kl_menu_pictures_1110.py - READ-ONLY picture inventory of Dog Days' menu scene (track T9, 2026-11-10, local partner).

For every ZWINPIC family of the LIVE themed menu scene copy: instances, W x H, tiles (.TEX id, size, format), whether
6b's stages A/B/C/F restyled its pixels (compared with the STOCK scene `<DD>\\Scenes\\kaneandlynch.zip`), and which
Window / GuiElement of frontend / ingame / online.xml name it (Graphic=, FocusGraphic=, child <Graphic>, also through
Template chains). ZWINGROUP is the scene's folder tree (Menu/Resources/Frames/Winpics/...): counted, not listed.

    python tools\\kl_menu_pictures_1110.py dump <out.md> [--dd DIR]

Needs numpy only through kl_menu_redesign_1110 (not for this listing). Never writes a game file.
"""
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kl_menu_inventory_1110 as I  # noqa: E402
import kl_menu_redesign_1110 as R  # noqa: E402
import kl_texmat as T  # noqa: E402

DD = R.DD_DEF


def fam(n):
    return re.sub(r'#\d+$', '', n)


def users(parsed):
    """{picture name: set((file, window, element label))} from Graphic / FocusGraphic attrs and child <Graphic> lists."""
    out = collections.defaultdict(set)
    for fname, windows in parsed:
        for w in windows:
            enames = {el['own'].get('Name') for el in w['elements']}
            for el in w['elements']:
                lab = '%s#%d%s' % (w['name'], el['idx'], ('(' + el['own']['Name'] + ')') if el['own'].get('Name') else '')
                for k in ('Graphic',):
                    if el['eff'].get(k):
                        out[el['eff'][k]].add((fname, lab))
                for g in el['gfx']:
                    if g not in enames:        # a child <Graphic> usually names another ELEMENT of the window (ToggleImages), not a picture
                        out[g].add((fname, lab))
    return out


def main(argv):
    if len(argv) < 2 or argv[0] != 'dump':
        print(__doc__)
        return 2
    dd = argv[argv.index('--dd') + 1] if '--dd' in argv else DD
    ov = os.path.join(dd, 'KLExpansion', 'Overlay')
    live = R.open_scene('dd', path=os.path.join(ov, 'Scenes', 'kaneandlynch_deadmen.zip'))
    stock = R.open_scene('dd', path=os.path.join(dd, 'Scenes', 'kaneandlynch.zip'))
    parsed = []
    for fname, zp, mem in (('frontend', os.path.join(ov, 'Patch01_rows12.zip'), 'menu/frontend.xml'),
                           ('ingame', os.path.join(ov, 'Patch01.zip'), 'menu/ingame.xml'),
                           ('online', os.path.join(ov, 'Scenes', 'kaneandlynch.zip'), 'Menu/online.xml')):
        w, _t, _s = I.parse(I.load(zp, mem))
        parsed.append((fname, w))
    use = users(parsed)
    # templates carrying Graphic= are instanced through elements (eff already resolves them); add Template-level refs
    base = R.open_scene('dd', path=os.path.join(ov, 'Scenes', 'kaneandlynch.zip'))     # the overlay copy WITHOUT the theme
    changed_tex, mod_tex = set(), set()
    for tid, t in live.tex.tex.items():
        b = base.tex.tex.get(tid)
        if b is None or b.entry != t.entry:
            changed_tex.add(tid)           # stage 1 fonts / 6b stages A, B, C, F (theme)
    for tid, t in base.tex.tex.items():
        s0 = stock.tex.tex.get(tid)
        if s0 is None or s0.entry != t.entry:
            mod_tex.add(tid)               # the mod's own earlier art (icons, lobby names, hero portraits...) vs the stock game scene

    fams = collections.OrderedDict()
    for name, plist in live.pics.items():
        fams.setdefault(fam(name), []).append(name)
    # resolve each XML picture name: exact (case-insensitive) instance name, else its family (without #NN) -> every instance of it
    # GUESS: the game's name lookup is case-insensitive and falls back to the family; neither was read from the exe.
    low = {n.lower(): n for n in live.pics}
    lowfam = {f.lower(): f for f in fams}
    fam_users = collections.defaultdict(set)
    unref_names = {}
    for g, us in use.items():
        if g.lower() in low:
            fam_users[fam(low[g.lower()])] |= {(a, b + ('' if g == low[g.lower()] else ' [case]')) for a, b in us}
        elif fam(g).lower() in lowfam:
            fam_users[lowfam[fam(g).lower()]] |= {(a, b + ' [fam]') for a, b in us}
        else:
            unref_names[g] = us
    lines = ['# Menu scene picture inventory (live `Overlay\\Scenes\\kaneandlynch_deadmen.zip`, 2026-11-10, local partner, no crash involved)', '',
             'Generated by tools/kl_menu_pictures_1110.py (read-only). Source scene = the themed copy the game opens with [MenuLook] DeadMen=1; '
             '"restyled" = at least one tile .TEX record differs from the STOCK `<DD>\\Scenes\\kaneandlynch.zip` (that is 6b stages A/B/C/F, plus stage-1 `--bars` if it was used). '
             'Users = windows/elements of frontend (rows12) / ingame / online.xml whose Graphic= / child <Graphic> equals an instance name (exact instance name; `[case]` = matched ignoring case, `[fam]` = matched by family without #NN; GUESS: the game does the same, not read from the exe). Element label = `Window#index(name)` as in the per-file tables.', '']
    lines.append('ZWINPIC entities parsed: %d instances in %d families; texture records %d (theme-changed vs un-themed overlay copy: %d, mod art vs stock: %d).' % (
        sum(len(v) for v in live.pics.values()), len(fams), len(live.tex.tex), len(changed_tex), len(mod_tex)))
    lines.append('')
    lines.append('| family | n | W x H | tiles (tex id: w x h fmt) | theme | mod art | users (file: window#idx(name)) |')
    lines.append('|---|---|---|---|---|---|---|')
    named = set()
    restyled_fams = []
    for f, names in fams.items():
        p0 = live.pics[names[0]][0]
        tiles = []
        rs = False
        ma = False
        for sp in p0['sprites']:
            t = live.tex.tex.get(sp['tex'])
            info = R.tex_info(t.entry) if t is not None else None
            tiles.append('%d: %dx%d %s' % (sp['tex'], info['w'], info['h'], info['fmt']) if info else '%d: ?' % sp['tex'])
            rs = rs or sp['tex'] in changed_tex
        # restyled if any instance's tile changed
        for n in names:
            for p in live.pics[n]:
                if any(sp['tex'] in changed_tex for sp in p['sprites']):
                    rs = True
                if any(sp['tex'] in mod_tex for sp in p['sprites']):
                    ma = True
        if rs:
            restyled_fams.append(f)
        ulist = sorted(fam_users.get(f, set()))
        shown = '; '.join('%s: %s' % x for x in ulist[:5]) + ('; ..%d more' % (len(ulist) - 5) if len(ulist) > 5 else '')
        sizes = sorted({(int(p['W']), int(p['H'])) for n in names for p in live.pics[n]})
        lines.append('| %s | %d | %s | %s | %s | %s | %s |' % (
            f, len(names), ','.join('%dx%d' % s for s in sizes[:3]) + ('..' if len(sizes) > 3 else ''),
            '; '.join(tiles[:4]) + ('; ..%d tiles' % len(tiles) if len(tiles) > 4 else ''), 'YES' if rs else '', 'yes' if ma else '', shown.replace('|', '/')))
    lines.append('')
    unref = sorted(unref_names)
    lines.append('## XML picture names with NO ZWINPIC of that exact name in the menu scene (%d)' % len(unref))
    lines.append('These resolve elsewhere (level archives carry LevelPicture_* / weapon / HUD pictures) or by family; GUESS: not in this scene.')
    lines.append('')
    for g in unref:
        lines.append('- `%s` (%s)' % (g, '; '.join('%s: %s' % x for x in sorted(unref_names[g])[:3])))
    lines.append('')
    lines.append('## Pictures in the scene that no menu XML names (%d families)' % len([f for f in fams if f not in fam_users]))
    lines.append(', '.join('`%s`' % f for f in fams if f not in fam_users))
    lines.append('')
    lines.append('Theme-restyled families (%d): %s' % (len(restyled_fams), ', '.join(restyled_fams)))
    import kl_scene
    import zipfile
    ents = list(kl_scene.read(zipfile.ZipFile(os.path.join(ov, 'Scenes', 'kaneandlynch_deadmen.zip')), 'Scenes/kaneandlynch').entities())
    parsed_idx = {p['entity'] for v in live.pics.values() for p in v}
    bad = [(e.name.decode('latin1'), e.parent.name.decode('latin1') if e.parent is not None else '') for i, e in enumerate(ents)
           if e.tid == R.ZWINPIC and i not in parsed_idx]
    lines.append('')
    lines.append('ZWINPIC entities the reader could not parse (no valid sprite chunk; empty stubs in DD, GUESS) - %d: %s' % (
        len(bad), ', '.join('%s (in %s)' % b for b in bad)))
    lines.append('ZWINGROUP entities in the scene: %d (the folder tree Menu/Resources/Frames/Winpics/Graphic/..., each picture sits as `Box` under a group named like the picture).' % sum(1 for e in ents if e.tid == R.ZWINGROUP))
    open(argv[1], 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print(len(fams), 'families', len(changed_tex), 'changed tex', len(unref), 'unref names')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
