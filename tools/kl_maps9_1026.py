#!/usr/bin/env python3
"""
Generates the per-map System Link bench inis of C:/kl_build_1024/maps9_1026/ (derived from lan_1025/L9d_host.ini + L9d_join.ini).

    python tools/kl_maps9_1026.py [--out C:/kl_build_1024/maps9_1026] [--lan C:/kl_build_1024/lan_1025]

How a System Link host's map is chosen (klhook/klslot.c, re/fa_slots.md; see run_all.md):
  SLOT  = the host's lobby row MP_SelectedLevel (menu position 0..8 = F01 F02 F03 F04 F06 F07 F05 F08 F09), replicated to the clients.
          The lobby selector steps it with LEFT / RIGHT on the first row (GUESS: default focus; SL6..SL11 needed DOWN DOWN to reach 'Heist time').
  PAGE  = which map folder that slot loads (kls_page_now): [Expansion] Page=N (force, any state) beats OnlineSet beats the menu latch.
          Page 0 = stock Dog Days (DD01..DD09 via [Redirect]), 2 = [Redirect.2] Dead Men maps, 3 = [Redirect.3] Dead Men campaign maps.
          The page is read from EACH PEER'S OWN ini and is not sent (re/private_match_mapsync.md): the host and every joiner need the same Page.
          (F7 'map set' of klhostopt.c would send it, but only 0/2/9 and it was never run: not used here.)
Output per map:  M_<map>_host.ini (9 players), M2_<map>_host.ini (2 players), M_<map>_join.ini (= J_join.ini + that Page).
"""
import os, re, sys

SLOT_POS = {'F01': 0, 'F02': 1, 'F03': 2, 'F04': 3, 'F06': 4, 'F07': 5, 'F05': 6, 'F08': 7, 'F09': 8}
# (map folder, slot, page)  - from the installed KLHook.ini [Redirect] / [Redirect.2] / [Redirect.3] (2026-10-26)
MAPS = [('DD%02d' % i, 'F%02d' % i, 0) for i in range(1, 10)]
MAPS += [('DM01', 'F01', 2), ('DM02', 'F02', 2), ('DM03', 'F03', 2), ('DM06', 'F04', 2), ('DM09', 'F06', 2), ('DM03A', 'F07', 2)]
MAPS += [('DM05A', 'F01', 3), ('DM06B', 'F02', 3), ('DM01B', 'F03', 3), ('DM11B', 'F04', 3), ('DM07', 'F06', 3), ('DD10', 'F07', 3)]


def arg(name, default):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default


def host_ini(src, name, slot, page, n, observe_ms, sync):
    pre = ['; %s: %d players on %s (slot %s, page %d). Generated by tools/kl_maps9_1026.py from L9d_host.ini.' % (
        'M_' if n == 9 else 'M2_', n, name, slot, page),
        '[Expansion]', 'Page=%d' % page, 'Log=1', '[HUD]', 'Log=1']
    if sync:
        pre += ['[Sync]', 'Probe=1', 'Share=1', 'Every=5000']
    head, script = src.split('[Script]', 1)
    out, num, step = [], 0, False
    for l in script.splitlines():
        m = re.match(r'^\s*(\d+)=(.*)$', l)
        if not m:
            if l.strip(): out.append(l)
            continue
        cmd = m.group(2)
        if cmd.startswith('waitpeers'):
            cmd = 'waitpeers %d %d %d' % (n, 900000 if n > 2 else 600000, 30000 if n > 2 else 10000)
        if cmd.startswith('wait ') and cmd.split()[1] == '240000':
            cmd = 'wait %d' % observe_ms
        num += 1; out.append('%d=%s' % (num, cmd))
        if cmd.startswith('log SOLO host lobby'):
            # GUESS: the focus is on the map row and RIGHT steps MP_SelectedLevel one position (no wrap assumed: only RIGHT from position 0)
            for _ in range(SLOT_POS[slot]):
                num += 1; out.append('%d=tap RIGHT' % num)
                num += 1; out.append('%d=wait 900' % num)
            num += 1; out.append('%d=log MAPS9 map row stepped %d x RIGHT -> slot %s, expect LOAD %s page %d rule %s' % (num, SLOT_POS[slot], slot, slot, page, name))
            num += 1; out.append('%d=windows' % num)
    return '\n'.join(pre) + '\n' + head.rstrip() + '\n[Script]\n' + '\n'.join(out) + '\n'


def main():
    lan, outd = arg('--lan', 'C:/kl_build_1024/lan_1025'), arg('--out', 'C:/kl_build_1024/maps9_1026')
    os.makedirs(outd, exist_ok=True)
    host = open(os.path.join(lan, 'L9d_host.ini'), encoding='latin-1').read()
    join = open(os.path.join(lan, 'L9d_join.ini'), encoding='latin-1').read()
    # the shared joiner ini: L9d's '[Expansion] OnlineSet=0' would load STOCK maps on joiners against a Dead Men host, so it is dropped here
    join = re.sub(r'\[Expansion\]\s*\r?\nOnlineSet=0\s*\r?\n', '', join)
    open(os.path.join(outd, 'J_join.ini'), 'w', encoding='latin-1', newline='\n').write(
        '; shared joiner ini (L9d_join.ini without [Expansion] OnlineSet=0). The map Page is added per map: M_<map>_join.ini.\n' + join)
    for name, slot, page in MAPS:
        open(os.path.join(outd, 'M_%s_host.ini' % name), 'w', encoding='latin-1', newline='\n').write(host_ini(host, name, slot, page, 9, 300000, True))
        open(os.path.join(outd, 'M2_%s_host.ini' % name), 'w', encoding='latin-1', newline='\n').write(host_ini(host, name, slot, page, 2, 300000, False))
        open(os.path.join(outd, 'M_%s_join.ini' % name), 'w', encoding='latin-1', newline='\n').write(
            '; joiner for %s: Page=%d (slot %s comes from the host)\n[Expansion]\nPage=%d\nLog=1\n' % (name, page, slot, page) + join)
    print('wrote %d maps to %s' % (len(MAPS), outd))


if __name__ == '__main__':
    main()
