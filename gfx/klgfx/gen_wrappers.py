#!/usr/bin/env python3
"""
Generate d3d9_wrap.inl: forwarding bodies for every IDirect3D9 / IDirect3DDevice9 method, in
vtable order, from MinGW's d3d9.h (identical method order to the Windows SDK header).

    python gen_wrappers.py [path to d3d9.h]      (default /usr/share/mingw-w64/include/d3d9.h)

Methods listed in HAND are left out; klgfx.cpp writes those itself (logging, capture, the NR bridge).
The output is committed, so building does not need this script or MinGW's headers.
"""
import re, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/mingw-w64/include/d3d9.h'

HAND = {
    'IDirect3D9': {'QueryInterface', 'AddRef', 'Release', 'CreateDevice'},
    'IDirect3DDevice9': {
        'QueryInterface', 'AddRef', 'Release', 'GetDirect3D', 'Reset', 'Present',
        'SetRenderTarget', 'SetDepthStencilSurface', 'Clear', 'StretchRect', 'SetViewport',
        'BeginScene', 'EndScene', 'SetRenderState', 'SetTexture',
        'DrawPrimitive', 'DrawIndexedPrimitive', 'DrawPrimitiveUP', 'DrawIndexedPrimitiveUP',
        'CreateVertexShader', 'CreatePixelShader', 'SetVertexShader', 'SetPixelShader',
        'SetVertexShaderConstantF', 'SetPixelShaderConstantF',
        'CreateTexture', 'CreateRenderTarget', 'CreateDepthStencilSurface', 'ColorFill',
        'UpdateSurface', 'UpdateTexture', 'GetRenderTargetData', 'GetSwapChain',
    },
}


def methods(text, iface):
    m = re.search(r'DECLARE_INTERFACE_\(%s,\s*IUnknown\)\s*\{(.*?)\n\};' % iface, text, re.S)
    if not m:
        raise SystemExit('no %s in %s' % (iface, SRC))
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    body = re.sub(r'\s+', ' ', body)
    out = []
    for d in re.finditer(r'STDMETHOD(_)?\((?:([^,()]+),)?\s*(\w+)\)\s*\((.*?)\)\s*PURE;', body):
        ret = (d.group(2) or 'HRESULT').strip() if d.group(1) else 'HRESULT'
        name, params = d.group(3), d.group(4).strip()
        params = re.sub(r'^THIS_?\s*', '', params)
        plist = []
        for i, p in enumerate([x.strip() for x in params.split(',')] if params else []):
            toks = p.split()
            if len(toks) >= 2 and re.fullmatch(r'\**\w+', toks[-1]) and toks[-1].lstrip('*') not in (
                    'D3DLIGHT9', 'D3DPRIMITIVETYPE'):
                stars = len(toks[-1]) - len(toks[-1].lstrip('*'))
                typ, nm = ' '.join(toks[:-1]) + '*' * stars, toks[-1].lstrip('*')
            else:
                typ, nm = p, 'a%d' % i
            typ = typ.replace('WINBOOL', 'BOOL')
            plist.append((typ, nm))
        out.append((ret.replace('WINBOOL', 'BOOL'), name, plist))
    return out


def emit(iface, ms, cls, real):
    lines = ['// ---- %s: generated forwarding (gen_wrappers.py) ----' % iface]
    for ret, name, plist in ms:
        if name in HAND[iface]:
            continue
        sig = ', '.join('%s %s' % (t, n) for t, n in plist)
        args = ', '.join(n for _, n in plist)
        call = '%s->%s(%s)' % (real, name, args)
        if ret == 'void':
            lines.append('void STDMETHODCALLTYPE %s(%s) override { %s; }' % (name, sig, call))
        else:
            lines.append('%s STDMETHODCALLTYPE %s(%s) override { return %s; }' % (ret, name, sig, call))
    return lines


text = open(SRC, encoding='latin1').read()
d3d = methods(text, 'IDirect3D9')
dev = methods(text, 'IDirect3DDevice9')
assert len(d3d) == 17 and len(dev) == 119, (len(d3d), len(dev))
for iface, ms in (('IDirect3D9', d3d), ('IDirect3DDevice9', dev)):
    missing = HAND[iface] - {n for _, n, _ in ms}
    assert not missing, missing
out = ['// Generated by gen_wrappers.py from d3d9.h - do not edit by hand.',
       '#if defined(KLG_WRAP_D3D9)'] + emit('IDirect3D9', d3d, 'KLDirect3D9', 'real') + \
      ['#elif defined(KLG_WRAP_DEVICE)'] + emit('IDirect3DDevice9', dev, 'KLDevice9', 'real') + ['#endif', '']
open(os.path.join(HERE, 'd3d9_wrap.inl'), 'w').write('\n'.join(out))
print('IDirect3D9 %d methods, IDirect3DDevice9 %d methods; %d + %d written by hand' % (
    len(d3d), len(dev), len(HAND['IDirect3D9']), len(HAND['IDirect3DDevice9'])))
