"""mkranges.py [union.json]   writes klhook\\klranges.h: the address ranges of kl2.exe that its integrity checks hash.
Source: union.json of the range checker (<work>\\research\\agent_scripts\\f-tamper\\ceg_ranges.py, re\\antitamper.md): the
union of the 626 range sets read at 594 call sites, as [start, end) pairs. The hook compiles the table in and refuses, in
session-safe mode, any write that touches one of these ranges (klhook.c, klh_may_write). Re-run after ceg_ranges.py was
re-run; the header is checked in so that a build needs neither Python nor the game."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'tools'))


def main():
    if len(sys.argv) > 1:
        src = sys.argv[1]
    else:
        import kl_port_check
        src = os.path.join(kl_port_check.workdir(), 'research', 'agent_scripts', 'f-tamper', 'union.json')
    U = sorted(tuple(x) for x in json.load(open(src)))
    assert all(a < b for a, b in U) and all(U[i][1] <= U[i + 1][0] for i in range(len(U) - 1)), 'ranges overlap or are empty'
    tot = sum(b - a for a, b in U)
    out = ['/* klranges.h - GENERATED by mkranges.py from the range checker\'s union.json; do not edit.',
           '   kl2.exe build 0490 (TimeDateStamp 0x4c80f728): %d ranges, %d bytes hashed by the integrity checks' % (len(U), tot),
           '   (re\\antitamper.md section 2). [start, end) as virtual addresses at the image base 0x400000, ascending. */',
           '#define KLH_NHASHED %d' % len(U),
           'static const DWORD klh_hashed[KLH_NHASHED][2] = {']
    for i in range(0, len(U), 4):
        out.append('    ' + ' '.join('{ 0x%08x, 0x%08x },' % x for x in U[i:i + 4]))
    out.append('};')
    open(os.path.join(HERE, 'klranges.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
    print('klranges.h: %d ranges, %d bytes, %#x .. %#x' % (len(U), tot, U[0][0], U[-1][1]))


if __name__ == '__main__':
    main()
