"""mkstock.py   writes klhook\\klstock.h: the fingerprint of every STOCK Dog Days level archive.
klsteam.c compares the archive the game opens for a level with this table; a level that is not the stock level of
its slot never writes to Steam (leaderboard, stats, achievements - re\\leaderboard.md 4).
Fingerprint = (file size, FNV-1a 32 of the zip's central directory). The central directory holds every member's name,
sizes and CRC-32, so any changed member changes it; reading it costs a few kilobytes whatever the archive's size.
Source: <DD>\\Scenes\\Locations\\*\\*.zip except Loader_Sequence.zip. Where <DD>\\KL_PortBackup holds the same path
(the F01 test slot), THAT file is the stock one. Read only; nothing in the game folder is written.
ASSUMPTION: every level archive outside the F01 slot is as Steam installed it (the project never writes there).
Re-run after a game update; the header is checked in so that a build needs neither Python nor the game."""
import glob, os, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'tools'))


def fnv(b, h=2166136261):
    for c in b:
        h = ((h ^ c) * 16777619) & 0xffffffff
    return h


def fingerprint(p):
    """(size, hash, members) of a zip: the hash runs over the central directory exactly as stored."""
    size = os.path.getsize(p)
    with open(p, 'rb') as f:
        n = min(size, 65536 + 22); f.seek(size - n); tail = f.read(n)
        i = tail.rfind(b'PK\x05\x06')
        assert i >= 0, 'no end-of-central-directory record: ' + p
        count, cdsize, cdoff = struct.unpack_from('<HII', tail, i + 10)
        assert cdoff + cdsize <= size, 'central directory outside the file: ' + p
        f.seek(cdoff); cd = f.read(cdsize)
    return size, fnv(cd), count


def main():
    import kl_port_check
    dd = kl_port_check.find(kl_port_check.DD_GUESSES, kl_port_check.DD_EXE)
    rows = []
    for p in sorted(glob.glob(os.path.join(glob.escape(dd), 'Scenes', 'Locations', '*', '*.zip'))):
        rel = os.path.relpath(p, os.path.join(dd, 'Scenes', 'Locations'))
        if os.path.basename(p).lower() == 'loader_sequence.zip':
            continue
        bak = os.path.join(dd, 'KL_PortBackup', 'Scenes', 'Locations', rel)
        src = bak if os.path.isfile(bak) else p
        size, h, count = fingerprint(src)
        rows.append((rel.lower(), size, h, count, 'KL_PortBackup' if src == bak else 'Scenes'))
    out = ['/* klstock.h - GENERATED by mkstock.py; do not edit.',
           '   The stock level archives of Kane & Lynch 2: Dog Days (Steam, kl2.exe build 0490): key = path under',
           '   Scenes\\Locations, lower case; file size; FNV-1a 32 of the zip central directory. %d archives.' % len(rows),
           '   F01 is taken from KL_PortBackup when the slot holds a test build. */',
           '#define KLX_NSTOCK %d' % len(rows),
           'static const struct { const char *key; DWORD size, hash; } klx_stock[KLX_NSTOCK] = {']
    for key, size, h, count, where in rows:
        out.append('    { "%s", %uu, 0x%08xu },%s/* %d members, from %s */' % (key.replace('\\', '\\\\'), size, h, ' ' * max(1, 22 - len(key)), count, where))
        print('%-22s %10d %08x %3d members  (%s)' % (key, size, h, count, where))
    out.append('};')
    open(os.path.join(HERE, 'klstock.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
    print('klstock.h: %d archives' % len(rows))


if __name__ == '__main__':
    main()
